const DICTS: Record<LangCode, Dict> = { en: {}, hi: HI, sat: SAT, mun: MUN, ho: HO };

const STORAGE_KEY = "jsic-lang";

type Ctx = { lang: LangCode; setLang: (l: LangCode) => void; t: (text: string) => string };

const LanguageContext = createContext<Ctx>({
  lang: "en",
  setLang: () => {},
  t: (text) => text,
});

export function LanguageProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<LangCode>("en");

  useEffect(() => {
    const saved = window.localStorage.getItem(STORAGE_KEY) as LangCode | null;
    if (saved && DICTS[saved]) setLangState(saved);
  }, []);

  const setLang = useCallback((l: LangCode) => {
    setLangState(l);
    try {
      window.localStorage.setItem(STORAGE_KEY, l);
    } catch {
      /* storage unavailable */
    }
  }, []);

  const t = useCallback(
    (text: string) => {
      const dict = DICTS[lang];
      return dict[text] ?? text;
    },
    [lang],
  );

  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  return useContext(LanguageContext);
}

/** Convenience hook for components that only need the translate function. */
export function useT() {
  return useContext(LanguageContext).t;
}
